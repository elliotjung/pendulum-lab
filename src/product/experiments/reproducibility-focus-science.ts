export type ReproducibilityOutput = Pick<ResearchFocusResult, 'metrics' | 'tables' | 'charts' | 'warnings'>;
export const researchMetric = (
  id: string,
  label: string,
  value: number,
  unit = '1'
): ResearchFocusResult['metrics'][number] => ({ id, label, value, unit });

/** Deterministic observations generated by the preserved engine, labelled as instructional data. */
export function reproducibilityNativeRun(id: string, f: ResearchFields, gravity = f.g!) {
  const base = reproducibilityPlanarConfig(id, f),
    config = { ...base, parameters: { ...base.parameters, g: gravity } };
  const native = createPlanarSimulation(config),
    samples = [native.snapshot()];
  while (!native.done) samples.push(native.step());
  const actual = toCanonicalPlanar(config);
  if (!actual.ok) throw new Error('관측 생성용 실제 입력이 유효하지 않습니다.');
  return { config, samples, series: createDiagnosticSeries(actual.value, samples) };
}

function batchExperiment(id: string, f: ResearchFields, progress: (fraction: number) => void): ReproducibilityOutput {
  const canonical = reproducibilityFocusCanonical(id, f),
    kinds: BatchKind[] = id === '8.1' ? ['paired'] : ['grid', 'log', 'lhs', 'ensemble'];
  const metrics: ResearchFocusResult['metrics'][number][] = [],
    tables: ResearchFocusResult['tables'][number][] = [],
    charts: ResearchFocusResult['charts'][number][] = [],
    warnings: string[] = [];
  kinds.forEach((kind, index) => {
    const count = f.count ?? 2,
      defaults = defaultBatchSettings(canonical);
    const plan = buildBatch(canonical, {
      ...defaults,
      kind,
      count,
      concurrency: 1,
      seed: `s27-${f.seed}`,
      axes: [
        {
          group: 'initialConditions',
          key: 'theta1',
          start: kind === 'paired' ? f.theta1! : 0.1,
          end: kind === 'paired' ? f.theta1! + f.delta! : 1,
          count
        }
      ]
    });
    const states: BatchRunState[] = plan.runs.map((run, i) => {
      const result = executeBatchRun({ batchId: plan.id, run });
      progress((index + (i + 1) / plan.runs.length) / kinds.length);
      return { id: run.id, index: run.index, status: 'completed', attempts: 1, progress: 1, result };
    });
    const aggregate = aggregateBatch(plan, states);
    tables.push({
      id: `design-${kind}`,
      title: `${kind} · 실제 run과 입력 계보`,
      columns: ['run', '시작 theta1 (rad)', '끝 theta1 (rad)', 'steps', '원 입력 ID'],
      rows: plan.runs.map((run, i) => [
        run.id,
        (run.experiment.initialConditions.theta1 as { value: number }).value,
        states[i]!.result!.summary.metrics[0]!.final,
        states[i]!.result!.summary.steps,
        plan.sourceInputId
      ])
    });
    charts.push({
      id: `response-${kind}`,
      title: `${kind}의 제한된 응답`,
      xLabel: '시작 theta1 (rad)',
      yLabel: '끝 theta1 (rad)',
      mode: 'scatter',
      series: [
        {
          label: kind,
          points: plan.runs.map((run, i) => ({
            x: (run.experiment.initialConditions.theta1 as { value: number }).value,
            y: states[i]!.result!.summary.metrics[0]!.final
          }))
        }
      ]
    });
    metrics.push(
      researchMetric(`${kind}-completed`, `${kind} 완료 run`, aggregate.completed),
      researchMetric(
        `${kind}-endpoint-sd`,
        `${kind} endpoint 표본 표준편차`,
        aggregate.metrics[0]!.standardDeviation,
        'rad'
      )
    );
    if (aggregate.pairedDifference)
      metrics.push(
        researchMetric('paired-difference', '비교군−대조군 endpoint 차이', aggregate.pairedDifference[0]!.value, 'rad')
      );
    warnings.push(...aggregate.warnings);
  });
  return { metrics, tables, charts, warnings: [...new Set(warnings)] };
}

async function observationsExperiment(id: string, f: ResearchFields): Promise<ReproducibilityOutput> {
  const truth = reproducibilityNativeRun(id, f, id === '8.3' ? f.truthG! : f.g!);
  const text = [
    't,a,b',
    ...truth.samples.map(
      (s, i) =>
        `${s.time},${s.state[0]! + (f.noise ?? 0) * Math.sin(i * 1.37)},${s.state[1]! + (f.noise ?? 0) * Math.cos(i * 1.13)}`
    )
  ].join('\n');
  if (id === '8.3') {
    const observation = confirmObservationImport(
      await previewObservationImport({
        kind: 'csv',
        name: 'instructional-native-run.csv',
        text,
        mapping: { time: 't', theta1: 'a', theta2: 'b' }
      })
    );
    const request = {
      schema: 'pendulum-inverse-request/v1' as const,
      id: 'learn_8_3',
      experiment: reproducibilityFocusCanonical(id, f),
      settings: {
        ...defaultEstimateSettings(observation),
        maxIterations: f.iterations!,
        parameters: [{ key: 'g' as const, min: 5, max: 15 }]
      }
    };
    const result = await runInverse(request),
      fit = result.payload.fit as { rmse: number; converged: boolean; iterations: number };
    return {
      metrics: [
        researchMetric('estimated-g', '국소 추정 중력', result.rows[0]![1]!, 'm/s^2'),
        researchMetric('truth-g', '관측 생성 중력', f.truthG!, 'm/s^2'),
        researchMetric('observation-rmse', '관측 잔차 RMSE', fit.rmse, 'rad'),
        researchMetric('converged', 'native 수렴 (1=참)', Number(fit.converged)),
        researchMetric('iterations', 'native 보정 반복', fit.iterations)
      ],
      tables: [
        {
          id: 'fit',
          title: '실제 국소 추정',
          columns: result.columns.map((c, i) => `${c} (${result.units[i]})`),
          rows: result.rows
        },
        {
          id: 'observation-lineage',
          title: '합성 관측 원본·변환 계보',
          columns: ['항목', '식별자'],
          rows: [
            ['observation', observation.id],
            ['original sha256', observation.original.sha256],
            ['transform', observation.transform.id],
            ['inverse input', result.inputId]
          ]
        }
      ],
      charts: [],
      warnings: [
        ...result.warnings,
        '결정론적 native 진자 기록에 명시적 sin/cos 교란을 더한 교육 자료입니다. 실측·확률 posterior가 아니며 truth는 추정기에 전달하지 않습니다.'
      ]
    };
  }
  const previews = await Promise.all(
    (['csv', 'sensor'] as const).map((kind) =>
      previewObservationImport({
        kind,
        name: `instructional-${kind}.csv`,
        text: [
          'ms,a,b',
          ...truth.samples.map(
            (s) => `${s.time * 1000},${(s.state[0]! * 180) / Math.PI},${(s.state[1]! * 180) / Math.PI}`
          )
        ].join('\n'),
        mapping: { time: 'ms', theta1: 'a', theta2: 'b' },
        options: {
          timeUnit: 'ms',
          angleUnit: 'deg',
          timeScale: f.clockScale!,
          angleScale: [f.angleScale!, f.angleScale!]
        }
      })
    )
  );
  const confirmed = previews.map(confirmObservationImport);
  return {
    metrics: [
      researchMetric('accepted-rows', '각 importer 승인 표본', confirmed[0]!.data.times.length),
      researchMetric('calibrated-end-time', '변환한 마지막 시간', confirmed[0]!.data.times.at(-1)!, 's'),
      researchMetric(
        'source-unchanged',
        'CSV 원본 bytes 유지',
        Number(confirmed[0]!.original.text === previews[0]!.artifact.original.text)
      )
    ],
    tables: [
      {
        id: 'import-lineage',
        title: 'preview 확인 후 승인된 CSV·sensor',
        columns: ['종류', '원본 SHA256', '변환 ID', '각도 단위', '시간 단위'],
        rows: confirmed.map((o) => [
          o.original.kind,
          o.original.sha256,
          o.transform.id,
          o.data.angleUnit,
          o.data.timeUnit
        ])
      },
      {
        id: 'calibrated-observations',
        title: 'calibration 뒤 관측',
        columns: ['시간 (s)', 'theta1 (rad)', 'theta2 (rad)'],
        rows: confirmed[0]!.data.times.map((t, i) => [t, ...confirmed[0]!.data.angles[i]!])
      }
    ],
    charts: [
      {
        id: 'calibrated-curve',
        title: '변환 뒤 첫 각도',
        xLabel: '시간 (s)',
        yLabel: 'theta1 (rad)',
        series: [
          {
            label: 'CSV',
            points: confirmed[0]!.data.times.map((x, i) => ({ x, y: confirmed[0]!.data.angles[i]![0]! }))
          }
        ]
      }
    ],
    warnings: [
      '결정론적 공용 엔진 기록을 ms·deg로 표시한 교육 CSV/sensor 자료입니다. 실제 센서 오차·영상 추적 실패를 측정한 자료가 아닙니다.',
      '영상 해독·색상 추적은 브라우저 문서가 필요한 전체 Lab 가져오기에서 수행합니다. 이 worker 실험은 영상이나 가짜 media 원본을 만들지 않습니다. 시간 보간·결측 대체는 자동으로 적용하지 않습니다.'
    ]
  };
}

async function uqExperiment(
  id: string,
  f: ResearchFields,
  progress: (fraction: number) => void
): Promise<ReproducibilityOutput> {
  const experiment = reproducibilityFocusCanonical(id, f),
    kind = id === '8.5' ? 'sobol' : 'pce';
  const result = await runInverse(
    {
      schema: 'pendulum-inverse-request/v1',
      id: `learn_${id.replace('.', '_')}`,
      experiment,
      settings: {
        ...defaultInverseSettings(experiment, kind),
        variables: [{ group: 'parameters', key: 'g', min: f.g! - f.halfRange!, max: f.g! + f.halfRange! }],
        samples: f.samples!,
        degree: f.degree ?? 2,
        seed: `s27-${f.seed}`
      }
    },
    (p) => {
      if (p.fraction !== null) progress(p.fraction);
    }
  );
  const metrics = [researchMetric('forward-evaluations', '실제 전방 평가', result.evaluations)],
    tables: ResearchFocusResult['tables'][number][] = [
      {
        id: 'native-uq',
        title: '공용 UQ 결과',
        columns: result.columns.map((c, i) => `${c} (${result.units[i]})`),
        rows: result.rows
      }
    ];
  const charts: ResearchFocusResult['charts'][number][] = [];
  if (kind === 'pce') {
    const validation = result.payload.validation as { inputs: number[]; output: number; predicted: number }[];
    metrics.push(
      researchMetric('validation-rmse', '별도 LHS validation RMSE', result.payload.validationRmse as number, 'rad'),
      researchMetric(
        'surrogate-at-baseline',
        'baseline g의 surrogate 예측',
        predictSurrogateResult(result, [f.g!]),
        'rad'
      )
    );
    tables.push({
      id: 'held-out',
      title: '훈련과 다른 설계의 validation',
      columns: ['g (m/s²)', 'native endpoint (rad)', 'surrogate (rad)', '잔차 (rad)'],
      rows: validation.map((v) => [v.inputs[0]!, v.output, v.predicted, v.predicted - v.output])
    });
    charts.push({
      id: 'held-out-scatter',
      title: '보지 않은 입력의 endpoint 예측',
      mode: 'scatter',
      xLabel: 'native endpoint (rad)',
      yLabel: 'surrogate (rad)',
      series: [{ label: 'validation', points: validation.map((v) => ({ x: v.output, y: v.predicted })) }]
    });
  }
  return {
    metrics,
    tables,
    charts,
    warnings: [
      ...result.warnings,
      '단일 독립 균등 입력 g의 예입니다. 작은 표본의 Sobol 지수를 0..1로 자르지 않으며 여러 입력의 상호작용·상관을 이 예가 검증하지 않습니다.'
    ]
  };
}

export async function executeReproducibilityFocus(
  id: string,
  input: ResearchFields,
  progress: (fraction: number) => void = () => undefined
): Promise<ResearchFocusResult> {
  const fields = reproducibilityFocusFields(id, input),
    canonical = reproducibilityFocusCanonical(id, fields);
  progress(0);
  const output = ['8.1', '8.2'].includes(id)
    ? batchExperiment(id, fields, progress)
    : ['8.3', '8.4'].includes(id)
      ? await observationsExperiment(id, fields)
      : ['8.5', '8.6'].includes(id)
        ? await uqExperiment(id, fields, progress)
        : ['8.7', '8.8', '8.9', '8.10'].includes(id)
          ? await reproducibilityLearning(id, fields, canonical)
          : await reproducibilityProject(id, fields, canonical);
  progress(1);
  return { schema: 'pendulum-research-focus/v1', unitId: id, fields, canonical, ...output };
}
